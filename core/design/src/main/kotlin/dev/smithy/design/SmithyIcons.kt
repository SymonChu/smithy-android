/**
 * 把 Material Symbols 的 path 数据包成 [ImageVector]。
 *
 * **平移那一层是必须的**：官方 24px 变体的坐标网格是 `viewBox="0 -960 960 960"`，
 * y 轴画在 0 以上、成负数（比如整个「文件夹」落在 y = -800..-160）。ImageVector 的
 * 视口没有原点偏移，直接塞进去整张图会跑到可视区外面 —— 表现为「图标是空的」。
 * 平移 +960 把它搬回 0..960。
 *
 * 注意 `addGroup` **不带块参数**（Compose 1.7 的 `ImageVector.Builder` 上没有
 * `block` 这个参数，写成 `addGroup(...) { ... }` 会把 lambda 当 `clipPathData` 传进去
 * 而报类型错）。它的语义是「压一个新组，之后的节点都挂进这个组」，所以平移到组之后、
 * 加路径之前设置。
 */
private fun smithyIcon(name: String, pathData: String): ImageVector =
    ImageVector.Builder(
        name = "SmithyIcons.$name",
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 960f,
        viewportHeight = 960f,
    ).apply {
        addGroup(translationY = 960f)
        addPath(
            pathData = PathParser().parsePathString(pathData).toNodes(),
            // 填默认色即可：Icon 的 tint 走 ColorFilter，会把整条路径重新着色
            fill = SolidColor(Color.Black),
        )
    }.build()
